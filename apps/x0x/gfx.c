void gfx_bind(uint8_t *fb) { g_fb = fb; }

void gfx_clear(void)
{
    for (int i = 0; i < GFX_W * GFX_H / 8; i++)
        g_fb[i] = 0;
}

void gfx_px(int x, int y, int on)
{
    uint8_t *b, m;
    if ((unsigned)x >= GFX_W || (unsigned)y >= GFX_H)
        return;
    b = &g_fb[(y >> 3) * GFX_W + x];
    m = (uint8_t)(1u << (y & 7));
    if (on == 2)
        *b ^= m;
    else if (on)
        *b |= m;
    else
        *b &= (uint8_t)~m;
}

void gfx_fill(int x, int y, int w, int h, int on)
{
    for (int j = y; j < y + h; j++)
        for (int i = x; i < x + w; i++)
            gfx_px(i, j, on);
}

void gfx_frame(int x, int y, int w, int h)
{
    gfx_fill(x, y, w, 1, 1);
    gfx_fill(x, y + h - 1, w, 1, 1);
    gfx_fill(x, y, 1, h, 1);
    gfx_fill(x + w - 1, y, 1, h, 1);
}

int gfx_text(int x, int y, const char *s, int inv)
{
    for (; *s; s++) {
        int c = (unsigned char)*s;
        if (c < 32 || c > 126)
            c = '?';
        for (int i = 0; i < 6; i++) {
            uint8_t col = i < 5 ? FONT[c - 32][i] : 0;
            for (int j = 0; j < 8; j++)
                if (((col >> j) & 1) != 0 || inv)
                    gfx_px(x + i, y + j, inv ? !((col >> j) & 1) : 1);
        }
        x += 6;
    }
    return x;
}

int gfx_text_w(const char *s)
{
    int n = 0;
    while (*s++)
        n++;
    return n * 6;
}
